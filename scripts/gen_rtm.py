"""Generate docs/14-traceability-matrix.md from the FR, NFR, BR and backlog documents and check ID consistency."""
import re, sys
from pathlib import Path
from collections import defaultdict
D = Path(__file__).resolve().parents[1] / "docs"

fr_rows = {}
for line in (D/"03-functional-requirements.md").read_text().splitlines():
    m = re.match(r"\| (FR-[A-Z]+-\d+) \| (.+?) \| ([MO]) \| (P\d) \| (\d) \| (.+?) \| (.+?) \|$", line)
    if m: fr_rows[m.group(1)] = dict(text=m.group(2), type=m.group(3), pri=m.group(4), phase=m.group(5), spec=m.group(6), rules=m.group(7))
nfr = set(re.findall(r"\| (NFR-[A-Z0-9]+-\d+) \|", (D/"04-non-functional-requirements.md").read_text()))
br_text = (D/"05-business-rules.md").read_text()
rules = set(re.findall(r"\b(BR-[A-Z]+-\d+)\b", br_text))

stories, covers = {}, defaultdict(set)
cur = None
for line in (D/"12-backlog.md").read_text().splitlines():
    m = re.match(r"### ([A-Z]+-\d+) · (.+) \((P\d), Phase ([\d→]+)\)", line)
    if m: cur = m.group(1); stories[cur] = dict(title=m.group(2), pri=m.group(3), phase=m.group(4), ac=0); continue
    if cur and line.startswith("Covers:"):
        for i in re.findall(r"\b((?:FR|NFR|BR)-[A-Z0-9]+-\d+)\b", line): covers[i].add(cur)
    if cur and re.match(r"- AC\d", line): stories[cur]["ac"] += 1

errors = []
for i in covers:
    if i.startswith("FR-") and i not in fr_rows: errors.append(f"Story references unknown {i}")
    if i.startswith("NFR-") and i not in nfr: errors.append(f"Story references unknown {i}")
    if i.startswith("BR-") and i not in rules: errors.append(f"Story references unknown {i}")
uncovered_fr = [f for f in fr_rows if f not in covers]
uncovered_nfr = [n for n in sorted(nfr) if n not in covers]
no_ac = [s for s,v in stories.items() if v["ac"] == 0]
tests = {"FR-WO-03":"TC-CRIT-05, TC-XPROG-01, TC-SETS-01, TC-SKIP-01, TC-SAMEDAY-01, TC-FIRST-01","FR-WO-04":"TC-CRIT-06/07",
         "FR-WO-14":"TC-CRIT-08…10","FR-PWA-02":"TC-CRIT-11","FR-AN-01":"TC-CRIT-12","FR-PR-01":"TC-CRIT-12","FR-BAK-01":"TC-CRIT-13",
         "FR-BAK-02":"TC-CRIT-14/15, TC-RESTORE-BAD-01","FR-MIG-05":"TC-MIG-01","FR-MIG-01":"TC-MIG-02","FR-BAK-05":"TC-UPGRADE-01",
         "FR-TIMER-03":"TC-TIMER-01","FR-SET-01":"TC-UNIT-01","FR-WO-17":"TC-PAIN-01","FR-BODY-03":"TC-PRIV-01","FR-PROG-09":"TC-CRIT-07"}

out = ["# 14 — Requirements Traceability Matrix", "",
       "> Generated by `scripts/gen_rtm.py` from docs 03, 04, 05 and 12. Do not edit by hand.", "",
       f"**Coverage:** {len(fr_rows)} FRs · {len(nfr)} NFRs · {len(rules)} business rules · {len(stories)} stories · "
       f"{sum(v['ac'] for v in stories.values())} acceptance criteria · uncovered FRs: {len(uncovered_fr)} · uncovered NFRs: {len(uncovered_nfr)} · "
       f"stories without AC: {len(no_ac)} · reference errors: {len(errors)}", "",
       "| Spec § | FR | Requirement | Type | Pri | Phase | Business rules | Stories | Named tests | Status |",
       "|---|---|---|---|---|---|---|---|---|---|"]
for f,v in fr_rows.items():
    out.append(f"| {v['spec']} | {f} | {v['text']} | {v['type']} | {v['pri']} | {v['phase']} | {v['rules']} | {', '.join(sorted(covers[f]))} | {tests.get(f,'story AC')} | Not started |")
out += ["", "## NFR coverage", "", "| NFR | Stories |", "|---|---|"]
for n in sorted(nfr): out.append(f"| {n} | {', '.join(sorted(covers[n])) or '—'} |")
out += ["", "## Business rule coverage (stories that cite the rule explicitly)", "", "| Rule | Stories |", "|---|---|"]
for r in sorted(rules): out.append(f"| {r} | {', '.join(sorted(covers[r])) or 'via FR (see FR table)'} |")
if uncovered_fr or uncovered_nfr or errors or no_ac:
    out += ["", "## Gaps", ""] + [f"- Uncovered FR: {x}" for x in uncovered_fr] + [f"- Uncovered NFR: {x}" for x in uncovered_nfr] + [f"- {e}" for e in errors] + [f"- No AC: {s}" for s in no_ac]
(D/"14-traceability-matrix.md").write_text("\n".join(out) + "\n")
print(f"FR={len(fr_rows)} NFR={len(nfr)} BR={len(rules)} stories={len(stories)} AC={sum(v['ac'] for v in stories.values())}")
print("uncovered FR:", uncovered_fr); print("uncovered NFR:", uncovered_nfr); print("errors:", errors); print("no AC:", no_ac)
sys.exit(1 if (uncovered_fr or errors or no_ac) else 0)
